'use strict';

/** Export the local SQLite database as D1-compatible INSERT statements. */

const fs = require('node:fs');
const path = require('node:path');
const { DatabaseSync } = require('node:sqlite');

const DB_PATH = path.join(__dirname, '..', 'data', 'studysync.db');
const OUT_PATH = path.join(__dirname, 'd1-import.sql');

const db = new DatabaseSync(DB_PATH, { readOnly: true });

function q(value) {
    if (value === null || value === undefined) return 'NULL';
    if (typeof value === 'number') return String(value);
    return `'${String(value).replace(/'/g, "''")}'`;
}

function insertRows(table, columns, rows) {
    if (!rows.length) return '';
    const lines = rows.map(row =>
        `INSERT INTO ${table} (${columns.join(', ')}) VALUES (${columns.map(c => q(row[c])).join(', ')});`
    );
    return `\n-- ${table}: ${rows.length} rows\n${lines.join('\n')}\n`;
}

const migrations = db.prepare('SELECT version, name, applied_at FROM migrations ORDER BY version').all();
const subjects = db.prepare('SELECT id, name, position, created_at FROM subjects ORDER BY position, rowid').all();
const modules = db.prepare('SELECT id, subject_id, name, position FROM modules ORDER BY position, rowid').all();
const topics = db.prepare('SELECT id, module_id, name, completed, position FROM topics ORDER BY position, rowid').all();

const sql = [
    '-- StudySync data export for Cloudflare D1',
    '-- Generated by db/export-to-d1.js — do not edit by hand.',
    'PRAGMA foreign_keys = ON;',
    insertRows('migrations', ['version', 'name', 'applied_at'], migrations),
    insertRows('subjects', ['id', 'name', 'position', 'created_at'], subjects),
    insertRows('modules', ['id', 'subject_id', 'name', 'position'], modules),
    insertRows('topics', ['id', 'module_id', 'name', 'completed', 'position'], topics)
].join('\n');

fs.writeFileSync(OUT_PATH, sql, 'utf8');
console.log(`Exported ${subjects.length} subjects, ${modules.length} modules, ${topics.length} topics to ${OUT_PATH}`);
