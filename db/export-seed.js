'use strict';

/** Generate seed-data.js so the static Pages build can show the curriculum. */

const fs = require('node:fs');
const path = require('node:path');
const { CURRICULUM, PRE_COMPLETED } = require('./seed');

function id(part) {
    return `seed-${part.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '')}`;
}

const subjects = CURRICULUM.map(subject => ({
    id: id(subject.name),
    name: subject.name,
    modules: subject.modules.map(([moduleName, topicNames]) => ({
        id: id(`${subject.name}-${moduleName}`),
        name: moduleName,
        topics: topicNames.map(topicName => ({
            id: id(`${subject.name}-${moduleName}-${topicName}`),
            name: topicName,
            completed: PRE_COMPLETED.has(topicName)
        }))
    }))
}));

const output = path.join(__dirname, '..', 'seed-data.js');
fs.writeFileSync(
    output,
    '/* Generated by db/export-seed.js — do not edit by hand. */\n' +
    'window.STUDYSYNC_SEED = ' + JSON.stringify(subjects, null, 2) + ';\n'
);
console.log(`Wrote ${output} (${subjects.length} subjects).`);
